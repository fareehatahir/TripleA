#!/usr/bin/env node
// Regenerates prisma/postgres/schema.prisma from the main schema (same models, provider = postgresql).
// With --baseline it also rewrites the single baseline migration. Use --baseline ONLY before the first
// production deploy; afterwards add migrations with:
//   DATABASE_URL=postgresql://… npx prisma migrate dev --name <change> --schema prisma/postgres/schema.prisma
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const src = readFileSync("prisma/schema.prisma", "utf8");
const out = src
  .replace(/^(\/\/[^\n]*\n)+/, "// GENERATED from prisma/schema.prisma by scripts/pg-sync.mjs (provider = postgresql). Do not edit by hand.\n")
  .replace(/(datasource db \{[^}]*provider\s*=\s*)"sqlite"/, '$1"postgresql"');
mkdirSync("prisma/postgres", { recursive: true });
writeFileSync("prisma/postgres/schema.prisma", out);
console.log("wrote prisma/postgres/schema.prisma");

if (process.argv.includes("--baseline")) {
  rmSync("prisma/postgres/migrations", { recursive: true, force: true });
  mkdirSync("prisma/postgres/migrations/20261023000000_init", { recursive: true });
  const r = spawnSync("npx", ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/postgres/schema.prisma", "--script"], { encoding: "utf8" });
  if (r.status !== 0) { console.error(r.stderr); process.exit(1); }
  writeFileSync("prisma/postgres/migrations/20261023000000_init/migration.sql", r.stdout);
  writeFileSync("prisma/postgres/migrations/migration_lock.toml", '# Please do not edit this file manually\nprovider = "postgresql"\n');
  console.log("wrote baseline migration (" + r.stdout.split("\n").length + " lines)");
}
